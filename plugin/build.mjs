#!/usr/bin/env node
/**
 * Assemble the Sidebar Spider DSH client plugin bundle.
 *
 * Inputs
 *   ../embed/spider-widget.js   compact Canvas spider view (generated from embed/)
 *   ../scene/scene.js           full-screen dashboard scene (optional; same engine port)
 *   ./src/plugin.js                    browser-half plugin source (uses `require("react")`)
 *
 * Output
 *   ./lib/client.js                    lazy-CJS DSH client bundle:
 *                                      window.__ModuleLoader__.load({ id, factory })
 *
 * Run:  node build.mjs
 */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const WIDGET = path.resolve(__dirname, "../embed/spider-widget.js");
const SCENE = path.resolve(__dirname, "../scene/scene.js");
const SOURCE = path.resolve(__dirname, "src/plugin.js");
const PKG_DIR = path.resolve(__dirname);
const OUT = path.resolve(PKG_DIR, "lib/client.js");

const pkg = JSON.parse(fs.readFileSync(path.resolve(PKG_DIR, "package.json"), "utf8"));
const pluginSource = fs.readFileSync(SOURCE, "utf8");

/**
 * Embed an engine-style IIFE (`(function (root) { ... })(globalThis)`) so its
 * global export becomes a factory-scoped constant instead of a global, and its
 * CommonJS tail cannot clobber our module.exports.
 */
function embedIife(file, globalName, constName) {
  const source = fs.readFileSync(file, "utf8");
  const patterns = [
    "})(typeof globalThis !== 'undefined' ? globalThis : typeof window !== 'undefined' ? window : this);",
    "})(typeof globalThis !== \"undefined\" ? globalThis : typeof window !== \"undefined\" ? window : this);"
  ];
  const invocation = patterns.find((candidate) => source.includes(candidate));
  if (!invocation) {
    throw new Error(`${path.basename(file)}: IIFE invocation marker not found (engine layout changed?)`);
  }
  const patched = source.replace(invocation, "})(__ROOT__);");
  return `// ===== BEGIN embedded ${path.basename(file)} (MIT, this repository) =====
var ${constName} = (function () {
  var __ROOT__ = {};
  var module = { exports: {} };
  var exports = module.exports;
${patched}
  if (module.exports && typeof module.exports.${globalName} === "function") return module.exports;
  if (typeof __ROOT__.${globalName} === "function") return { ${globalName}: __ROOT__.${globalName}, meta: __ROOT__.meta };
  return null;
})();
// ===== END embedded ${path.basename(file)} =====`;
}

const embeddedWidget = embedIife(WIDGET, "createSpiderView", "SPIDER");
const sceneExists = fs.existsSync(SCENE);
const embeddedScene = sceneExists
  ? embedIife(SCENE, "createSpiderScene", "SPIDER_SCENE")
  : "var SPIDER_SCENE = null;";

const bundle = `// Sidebar Spider — DSH client plugin bundle (generated by build.mjs; do not edit).
// id must equal package.json "name"; the shell resolves platform modules by name.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

${embeddedWidget}

${embeddedScene}

${pluginSource}

    return module.exports;
  }
});
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, bundle, "utf8");

const sha = crypto.createHash("sha256").update(bundle).digest("hex");
const meta = {
  generatedBy: "spider-plugin/build.mjs",
  plugin: pkg.name,
  version: pkg.version,
  bundle: path.relative(__dirname, OUT).replaceAll("\\", "/"),
  bytes: Buffer.byteLength(bundle, "utf8"),
  sha256: sha,
  widget: path.relative(__dirname, WIDGET).replaceAll("\\", "/"),
  scene: sceneExists ? path.relative(__dirname, SCENE).replaceAll("\\", "/") : null,
  generatedAt: new Date().toISOString()
};
fs.writeFileSync(path.resolve(__dirname, "build-meta.json"), JSON.stringify(meta, null, 2) + "\n", "utf8");
console.log(
  `[build] ${pkg.name} v${pkg.version} -> ${path.relative(__dirname, OUT)}  ` +
    `${(meta.bytes / 1024).toFixed(1)} KiB  scene=${sceneExists ? "yes" : "no"}  sha256=${sha.slice(0, 16)}…`
);
